from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from apk_sbom.ai_r8_assistant import (  # noqa: E402
    DEFAULT_METRICS_JSON,
    DEFAULT_SUGGESTIONS_JSON,
    DEFAULT_TRAINING_DATASET_JSON,
)


DEFAULT_OUTPUT_JSON = Path("data/results/evaluation/ai-r8-assistant-summary.json")
DEFAULT_OUTPUT_DOC = Path("docs/evaluation/AI_R8_ASSISTANT_SUMMARY.md")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build a compact thesis/demo summary for the AI R8 assistant.",
    )
    parser.add_argument(
        "--dataset-json",
        default=str(DEFAULT_TRAINING_DATASET_JSON),
        help="AI R8 training dataset JSON.",
    )
    parser.add_argument(
        "--metrics-json",
        default=str(DEFAULT_METRICS_JSON),
        help="AI R8 metrics JSON.",
    )
    parser.add_argument(
        "--suggestions-json",
        default=str(DEFAULT_SUGGESTIONS_JSON),
        help="AI R8 suggestions JSON.",
    )
    parser.add_argument(
        "--output-json",
        default=str(DEFAULT_OUTPUT_JSON),
        help="Compact summary JSON output.",
    )
    parser.add_argument(
        "--output-doc",
        default=str(DEFAULT_OUTPUT_DOC),
        help="Compact summary Markdown output.",
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()
    dataset = _load_json(args.dataset_json)
    metrics = _load_json(args.metrics_json)
    suggestions = _load_json(args.suggestions_json)
    summary = build_summary(dataset, metrics, suggestions)

    output_json = Path(args.output_json)
    output_doc = Path(args.output_doc)
    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_doc.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    output_doc.write_text(build_markdown(summary), encoding="utf-8")
    print(
        json.dumps(
            {
                "output_json": str(output_json),
                "output_doc": str(output_doc),
                "dataset_rows": summary["dataset"]["rows"],
                "suggestion_rows": summary["suggestions"]["suggestion_rows"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_summary(dataset: dict, metrics: dict, suggestions: dict) -> dict:
    test = metrics.get("test", {})
    baseline = metrics.get("baseline_comparison", {})
    return {
        "schema_version": "ai-r8-assistant-summary-v1",
        "report_only": True,
        "model": {
            "status": metrics.get("status"),
            "model_type": metrics.get("model_type"),
            "model_version": metrics.get("model_version"),
            "parameters": metrics.get("parameters", {}),
            "test_macro_f1": test.get("macro_f1"),
            "majority_baseline_test_accuracy": baseline.get("majority_class", {}).get(
                "test_accuracy"
            ),
            "score_threshold_baseline_test_accuracy": baseline.get(
                "score_threshold_rule",
                {},
            ).get("test_accuracy"),
            "split": metrics.get("split", {}),
        },
        "dataset": dataset.get("summary", {}),
        "suggestions": suggestions.get("summary", {}),
        "limits": [
            "AI output is report-only triage evidence.",
            "AI output cannot change selected versions, CycloneDX SBOM components, CVE labels, or source-validation metrics.",
            "Confirmed-exact rows are training labels only, not an AI authority in reports.",
            "Risk/mismatch separation remains the weakest class family and should be presented as future work.",
        ],
        "sources": {
            "dataset": dataset.get("sources", {}),
            "metrics_json": str(DEFAULT_METRICS_JSON),
            "suggestions_json": str(DEFAULT_SUGGESTIONS_JSON),
        },
    }


def build_markdown(summary: dict) -> str:
    model = summary["model"]
    dataset = summary["dataset"]
    suggestions = summary["suggestions"]
    lines = [
        "# AI R8 Assistant Summary",
        "",
        "Generated by `scripts/build_ai_r8_summary_export.py`.",
        "",
        "This compact artifact is for thesis/demo use. It summarizes the trained Phase 6A report-only ML assistant without requiring readers to open the large training dataset.",
        "",
        "## Model",
        "",
        f"- Status: `{model.get('status')}`",
        f"- Type: `{model.get('model_type')}`",
        f"- Version: `{model.get('model_version')}`",
        f"- Test macro-F1: `{model.get('test_macro_f1')}`",
        f"- Majority baseline test accuracy: `{model.get('majority_baseline_test_accuracy')}`",
        f"- Score-threshold baseline test accuracy: `{model.get('score_threshold_baseline_test_accuracy')}`",
        f"- Split: `{json.dumps(model.get('split', {}), sort_keys=True)}`",
        "",
        "## Dataset",
        "",
        f"- Rows: `{dataset.get('rows', 0)}`",
        f"- Case IDs: `{dataset.get('case_ids', 0)}`",
        f"- Coordinates: `{dataset.get('coordinates', 0)}`",
        "",
        "| Label | Rows |",
        "|---|---:|",
    ]
    for label, count in sorted(dataset.get("labels", {}).items()):
        lines.append(f"| `{label}` | {count} |")
    lines.extend(
        [
            "",
            "## Suggestions",
            "",
            f"- Suggestion rows: `{suggestions.get('suggestion_rows', 0)}`",
            f"- Recommendation counts: `{json.dumps(suggestions.get('recommendation_counts', {}), sort_keys=True)}`",
            "",
            "## Guardrails",
            "",
        ]
    )
    for limit in summary["limits"]:
        lines.append(f"- {limit}")
    lines.append("")
    return "\n".join(lines)


def _load_json(path: str | Path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


if __name__ == "__main__":
    raise SystemExit(main())

