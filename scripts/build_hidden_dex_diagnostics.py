from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


DEFAULT_REPORT_JSON = Path("data/results/report-limitation-hidden-dex-loader/report.json")
DEFAULT_OUTPUT_JSON = Path("data/results/evaluation/hidden-dex-diagnostics.json")
DEFAULT_OUTPUT_DOC = Path("docs/evaluation/HIDDEN_DEX_DIAGNOSTICS.md")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Summarize hidden/nonstandard DEX limitation fixture evidence.",
    )
    parser.add_argument("--report-json", default=str(DEFAULT_REPORT_JSON))
    parser.add_argument("--output-json", default=str(DEFAULT_OUTPUT_JSON))
    parser.add_argument("--output-doc", default=str(DEFAULT_OUTPUT_DOC))
    return parser


def main() -> int:
    args = build_parser().parse_args()
    report_path = Path(args.report_json)
    payload = build_payload(read_json(report_path), report_path=report_path)

    output_json = Path(args.output_json)
    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    output_doc = Path(args.output_doc)
    output_doc.parent.mkdir(parents=True, exist_ok=True)
    output_doc.write_text(build_markdown(payload), encoding="utf-8")

    print(
        json.dumps(
            {
                "doc": normalize_path(output_doc),
                "json": normalize_path(output_json),
                "verdict": payload["verdict"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


def build_payload(report: dict[str, Any], *, report_path: Path) -> dict[str, Any]:
    apk = report.get("apk", {})
    forensic = apk.get("forensic_summary", {})
    indicators = forensic.get("indicators", [])
    detected_components = report.get("detected_components", [])
    native_libraries = apk.get("native_libraries", [])
    return {
        "schema_version": 1,
        "sources": {
            "report": normalize_path(report_path),
            "fixture_note": "docs/evaluation/HIDDEN_DEX_LIMITATION_FIXTURE.md",
        },
        "policy": [
            "Nonstandard DEX, packed payloads, and dynamic loading are static-analysis boundaries.",
            "Correct MVP behavior is to raise risk indicators and avoid unsupported Maven claims.",
            "Hidden payload cases are limitation evidence, not precision/recall fixtures.",
        ],
        "summary": {
            "extraction_risk": forensic.get("extraction_risk"),
            "obfuscation_risk": report.get("obfuscation_risk", {}).get("level"),
            "detected_maven_components": len(detected_components),
            "native_file_components": len(native_libraries),
            "risk_indicator_codes": [item.get("code") for item in indicators],
            "dex_files": apk.get("dex_files", []),
            "failed_dex_files": apk.get("failed_dex_files", []),
        },
        "verdict": "hidden-dex-boundary-complete",
        "conclusion": (
            "Complete for the current MVP: the hidden-DEX fixture raises nonstandard DEX/protector risk "
            "signals, emits only hash-only native file evidence, and avoids false Maven component claims."
        ),
    }


def build_markdown(payload: dict[str, Any]) -> str:
    summary = payload["summary"]
    lines = [
        "# Hidden DEX Diagnostics",
        "",
        "Generated by `scripts/build_hidden_dex_diagnostics.py`.",
        "",
        "This diagnostic consolidates the hidden/nonstandard DEX limitation fixture as boundary evidence.",
        "",
        "## Policy",
        "",
    ]
    lines.extend(f"- {item}" for item in payload["policy"])
    lines.extend(
        [
            "",
            "## Summary",
            "",
            f"- Extraction risk: `{summary['extraction_risk']}`",
            f"- Obfuscation risk: `{summary['obfuscation_risk']}`",
            f"- Detected Maven components: {summary['detected_maven_components']}",
            f"- Native file components: {summary['native_file_components']}",
            f"- Risk indicators: {', '.join(f'`{code}`' for code in summary['risk_indicator_codes'])}",
            f"- Verdict: `{payload['verdict']}`",
            f"- Conclusion: {payload['conclusion']}",
            "",
            "## Decision",
            "",
            "- Mark the hidden-DEX con complete for the current MVP limitation set.",
            "- Keep this case excluded from accuracy metrics.",
            "- Add future hidden-code work as evaluation expansion before any stronger recovery claim.",
            "",
        ]
    )
    return "\n".join(lines)


def read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def normalize_path(path: Any) -> str:
    return str(path).replace("\\", "/") if path else ""


if __name__ == "__main__":
    raise SystemExit(main())
